const ORIGIN_EPILOGUES = {
  warden:
    "당신은 변경의 호송 일을 맡는다. 이번에는 명령받아 기억을 빼앗는 대신, 길을 잃은 사람을 집으로 데려온다.",
  scribe:
    "당신은 지워진 이름을 복원하는 기록법을 가르친다. 모르는 빈칸을 멋대로 채우지 않고, 그 사람을 기억하는 이의 말을 먼저 듣는다.",
  ranger:
    "당신은 안개벌과 왕도를 잇는 길에 표석을 세운다. 지도에는 길뿐 아니라 그 길에서 도움을 준 사람들의 이름도 남긴다.",
};
export class CampaignResolution {
  /** 증거는 결말의 우열 대신 어디까지 책임을 밝힐 수 있는지에 영향을 줍니다. */
  static evidenceCount(clues) {
    return FINAL_EVIDENCE.filter((clue) => clues.includes(clue)).length;
  }
  /** 모든 결말에서 구출·재판·기억의 대가와 동료들의 행방을 닫습니다. */
  static epilogue({ firstEnding, clues, originId }) {
    return [
      CampaignResolution.evidenceCount(clues) === FINAL_EVIDENCE.length
        ? "원본과 장부, 시민 증언이 서로를 입증했다. 칼드 렌과 수집을 승인한 관리들은 독립 재판에 선다. 어느 세력도 책임을 사제 한 사람에게 떠넘기지 못했다."
        : "실험 장부로 강제 수집은 밝혀졌다. 칼드는 재판에 섰지만 다른 승인자들의 책임까지 밝힐 증거는 부족했다. 피해자들은 서로 도우며 남은 이름을 찾아 기록한다.",
      clues.includes("칼드의 자백")
        ? "칼드는 자신의 명령이었음을 인정했다. 뒤늦은 고백이 피해를 없애지는 못하지만, 증인들이 다시 혼자 진실을 증명할 필요는 없었다."
        : "칼드는 왕국을 위한 선택이었다고 항변했다. 법정은 좋은 뜻이었다는 말보다, 실제로 빼앗긴 사람들의 삶을 먼저 들었다.",
      VILLAGE_EPILOGUES[firstEnding],
      "병든 왕은 병이 낫지 않은 채 퇴위한다. 빼앗은 기억으로 사람을 젊게 하거나 죽은 이를 되살릴 수는 없었다. 살아 있는 이에게는 기억을 돌려주고, 망자의 이름은 장례에서 읽었다.",
      "네라는 미르와 다시 식탁에 앉는다. 이벤은 둘 몫의 수프를 놓고, 토벤은 형편없는 농담을 한다. 에다는 종 도면을 나누고 세른은 노래를 가르친다. 리안은 주인에게 돌아갈 마지막 명부를 정리한다.",
      ORIGIN_EPILOGUES[originId],
      "일 년 뒤, 서리여울의 추수상에 당신의 자리가 마련된다. 네라가 등불을 들고 마중 나온다. 이번에는 서로의 이름을 아무도 잊지 않았다. 이야기는 여기서 끝난다. 기억하는 삶은 계속된다.",
    ];
  }
}
