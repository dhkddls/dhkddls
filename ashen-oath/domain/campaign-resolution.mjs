export class CampaignResolution {
  /** 증거 수만으로 선악 점수를 매기지 않고, 책임을 입증하는 구체성을 구분합니다. */
  static evidenceCount(clues) {
    return FINAL_EVIDENCE.filter((clue) => clues.includes(clue)).length;
  }

  /** 세 결말 공통으로 미해결 시한과 주요 인물의 행방을 마무리합니다. */
  static epilogue({ firstEnding, clues, originId }) {
    const evidence = CampaignResolution.evidenceCount(clues);
    const accountability =
      evidence === FINAL_EVIDENCE.length
        ? "왕실 원본, 시민 증언, 실험 장부가 서로를 입증한다. 칼드 렌과 반출을 승인한 감찰관들은 독립 재판에 선다. 왕관·교단·조합 누구도 책임을 사제 한 사람에게 떠넘기지 못했다."
        : "실험 장부로 강제 수집은 입증되었다. 칼드 렌은 재판에 섰지만 모든 승인자를 가리킬 증언은 부족했다. 시민들이 후속 조사에 참여하며 이름이 빠진 피해자들을 명부에 더한다. 끝난 모험 뒤에도 책임을 묻는 일은 사람들의 몫으로 남는다.";
    const confession = clues.includes("칼드의 자백")
      ? "칼드는 재판에서 명령이 자신의 것이었음을 다시 인정했다. 뒤늦은 고백이 피해를 지우지는 못했다."
      : "칼드는 기계가 왕국을 위한 선택이었다고 항변했다. 법정은 그의 의도가 아니라 강제로 빼앗은 기억과 명령의 책임을 물었다.";
    return [
      accountability,
      confession,
      VILLAGE_EPILOGUES[firstEnding],
      "병든 왕은 병이 낫지 않은 채 퇴위한다. 기억의 교환으로 젊음이나 죽은 사람을 되돌릴 수 있다는 약속은 거짓이었다. 회수한 기억은 살아 있는 당사자에게 동의를 받아 돌려주고, 망자의 원래 이름은 공개 장례에서 읽어 안식을 잇는다.",
      "네라는 미르와 함께 여관 식탁에 앉고, 이벤은 빈 의자의 주인이 누구였는지 이야기한다. 토벤의 형편없는 농담에 모두가 다시 웃는다. 에다는 종 도면을 여러 마을에 나누고 세른은 강 양편의 노래를 기록한다. 리안은 피해자들이 직접 고친 명부를 돌려준다. 누구도 혼자서 모두를 기억하라는 짐을 지지 않는다.",
      ORIGIN_EPILOGUES[originId],
      "일 년 뒤, 서리여울의 추수상에는 다시 빈 의자가 놓였다. 이번에는 누구를 위한 자리인지 모두가 안다. 네라가 당신에게 등불을 건넨다. 처음과 달리 그녀는 먼저 자기 이름을 말한다. 이야기는 여기서 끝난다. 기억하는 삶은 계속된다.",
    ];
  }
}
